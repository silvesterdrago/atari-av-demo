#!/usr/bin/env python3
"""Bake the shuriken: the spinning star from MonogAtari (Cerebral Vortex, SV2013).

Everything the show needs that is data rather than code, taken from the demo:

  * the star: 14 vertices, +-4 on each axis and the eight cube corners at +-1,
    and two sets of 12 triangles over them. One set is filled with backface
    culling, the other is drawn as wireframe over it, scaled up a little by
    a 16-step pulse, so the wire star breathes around the solid one.
  * cos/sin, 512 steps, int(256*cos) clamped to +-255 -- the demo's exact
    tables, so the rotation matrix comes out bit for bit the same.
  * the span filler: 2048 unrolled routines, one per (first pixel & 15, length
    0..127), each ORing the edge masks and storing d2 = -1 for the full words
    between, so a scanline of a triangle is one jump and no loop. The jump
    table has 8-byte entries (jmp abs.l + pad) so the index is (sh<<7|len)<<3.

    python3 tools/genshuriken.py        # writes src/shuriken.inc

Face indices are pre-multiplied by 4: they index the projected (x,y) word
pairs directly, which the demo did at init.
"""
import math

OUT = "src/shuriken.inc"

VERTS = [(1, 1, 1), (0, 4, 0), (-1, 1, 1), (-1, -1, 1), (0, -4, 0), (1, -1, 1),
         (4, 0, 0), (1, 1, -1), (-1, 1, -1), (-4, 0, 0), (0, 0, 4), (-1, -1, -1),
         (0, 0, -4), (1, -1, -1)]
FACES_FILL = [(0, 1, 2), (3, 4, 5), (0, 6, 7), (1, 7, 8), (8, 9, 2), (2, 3, 10),
              (10, 5, 0), (9, 11, 3), (12, 11, 8), (13, 12, 7), (5, 13, 6), (11, 13, 4)]
FACES_WIRE = [(11, 4, 3), (4, 13, 5), (5, 10, 3), (11, 12, 13), (0, 5, 6), (6, 13, 7),
              (1, 0, 7), (2, 10, 0), (9, 3, 2), (8, 2, 1), (8, 11, 9), (7, 12, 8)]
ZOOM = [79, 82, 84, 84, 84, 82, 79, 76, 73, 70, 68, 68, 68, 70, 73, 76]   # /64


def table(fn):
    return [max(-255, min(255, int(256 * fn(2 * math.pi * i / 512)))) for i in range(512)]


def span(sh, ln):
    """Instructions filling pixels [sh, sh+ln) from word (a5); d2 = -1."""
    end = sh + ln
    ins = []
    first = True
    pos = 0
    while pos < end:
        lo, hi = max(pos, sh), min(pos + 16, end)
        full = (lo == pos and hi == pos + 16)
        last = hi == end
        dst = "(a5)" if last else "(a5)+"
        if full:
            ins.append(f"    move.w  d2,{dst}")
        else:
            mask = ((0xffff >> (lo - pos)) & (0xffff << (pos + 16 - hi))) & 0xffff
            ins.append(f"    ori.w   #${mask:04x},{dst}")
        pos += 16
    ins.append("    rts")
    return ins


def words(seq, per=16):
    return ["    dc.w    " + ",".join(str(v) for v in seq[i:i + per]) for i in range(0, len(seq), per)]


def emit():
    out = ["; generated by tools/genshuriken.py -- do not edit", "",
           "    section text", "    even",
           "; span_tbl: jmp span_<sh>_<len>.l + pad, 8 bytes an entry", "span_tbl:"]
    for sh in range(16):
        for ln in range(128):
            out.append(f"    jmp     span_{sh}_{ln}.l")
            out.append("    dc.w    0")
    for sh in range(16):
        for ln in range(128):
            out.append(f"span_{sh}_{ln}:")
            out += span(sh, ln)
    out += ["", "    section data", "    even",
            "; mesh: nverts.l, verts.l, nfaces.l, faces.l; faces are index*4",
            "mesh_fill:", f"    dc.l    {len(VERTS)},star_verts,{len(FACES_FILL)},faces_fill",
            "mesh_wire:", f"    dc.l    {len(VERTS)},star_verts,{len(FACES_WIRE)},faces_wire",
            "star_verts:"]
    out += [f"    dc.w    {x},{y},{z}" for x, y, z in VERTS]
    out.append("faces_fill:")
    out += [f"    dc.w    {a*4},{b*4},{c*4}" for a, b, c in FACES_FILL]
    out.append("faces_wire:")
    out += [f"    dc.w    {a*4},{b*4},{c*4}" for a, b, c in FACES_WIRE]
    out += ["costab:"] + words(table(math.cos))
    out += ["sintab:"] + words(table(math.sin))
    out += ["zoomtab:", "    dc.b    " + ",".join(str(v) for v in ZOOM), ""]
    open(OUT, "w").write("\n".join(out))


if __name__ == "__main__":
    emit()
    print(f"wrote {OUT}")
